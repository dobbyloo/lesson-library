import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { config, repoRoot } from '../src/config.ts';
import { runDbmate } from '../src/migrate.ts';

// Writes db/schema.sql: the whole schema as it stands after every migration, in one
// readable file. Run it after adding a migration and commit the result; CI fails if the
// committed file is out of date.
//
// The dump comes from a scratch database migrated from nothing, not the development
// database, so it shows exactly what the migration files produce. pg_dump runs inside the
// Compose container, so nothing needs installing on the host.

const SCRATCH_DB = 'lesson_library_schema_dump';
const scratchUrl = new URL(config.databaseUrl);
scratchUrl.pathname = `/${SCRATCH_DB}`;

function inContainer(command: string[]): string {
  return execFileSync('docker', ['compose', 'exec', '-T', 'db', ...command], {
    cwd: repoRoot,
    encoding: 'utf8',
  });
}

inContainer(['dropdb', '-U', 'postgres', '--if-exists', SCRATCH_DB]);
try {
  // dbmate creates the database, then applies every migration
  runDbmate(scratchUrl.toString(), ['up'], { quiet: true });
  const dump = inContainer(['pg_dump', '-U', 'postgres', '--schema-only', '--no-owner', '--no-privileges', SCRATCH_DB]);

  // Drop the lines that differ from run to run or between Postgres patch releases, so the
  // file only changes when the schema does.
  const lines = dump
    .split('\n')
    .filter((line) => !line.startsWith('\\restrict') && !line.startsWith('\\unrestrict'))
    .filter((line) => !line.startsWith('-- Dumped from') && !line.startsWith('-- Dumped by'));
  const header = '-- Generated by `npm run schema:dump`. Do not edit; change the schema with a migration.\n\n';
  writeFileSync(`${repoRoot}db/schema.sql`, header + lines.join('\n').trimStart());
  console.log('Wrote db/schema.sql');
} finally {
  inContainer(['dropdb', '-U', 'postgres', '--if-exists', SCRATCH_DB]);
}
